// Σύνδεση: LED πίνακες → αντίστοιχος κωδικός εσωτερικής (και αντίστροφα)
(function(){
  Object.keys(T).forEach(function(k){
    var t = T[k]; if(!t.link || !T[t.link]) return;
    var tgt = T[t.link];
    t.codes.forEach(function(c){
      var ic = c[3]; if(!ic) { c[3]=null; return; }
      var list = (typeof ic === "string") ? [[ic, null]] : ic;
      var outs = [];
      list.forEach(function(pair, idx){
        var code = pair[0], hit = null;
        tgt.codes.forEach(function(x){ if(x[0].indexOf(code)>=0) hit = x; });
        outs.push(hit ? ("Εσωτερική "+code+": "+hit[1]) : ("Εσωτερική "+code));
        if(hit){
          var lbl = pair[1] || (t.pat ? patSym(c[0][0], t.pat.labels) : (k==="haier_outled" ? "LED1: "+c[0][0]+" αναλαμπές" : c[1].split("→")[0].trim()));
          hit[3] = (hit[3] ? hit[3]+" · " : "") + lbl;
          if(idx===0 && hit[2] && (!c[2] || k==="haier_outled")) c[2] = hit[2];
        }
      });
      c[4] = outs.join(" · ");
      c[3] = null;
    });
  });
  Object.keys(OUTX).forEach(function(k){
    var t = T[k]; if(!t) return; var m = OUTX[k];
    t.codes.forEach(function(c){ c[0].forEach(function(code){ if(m[code]) c[3] = m[code]; }); });
  });
})();
